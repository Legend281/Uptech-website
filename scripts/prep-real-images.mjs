const manifest = [];

for (const job of jobs) {
  const input = path.join(SRC, job.src);
  const buf = await sharp(input).webp({ quality: 82, effort: 6 }).toBuffer();
  const meta = await sharp(buf).metadata();
  const outFile = path.join(OUT, `${job.out}.webp`);
  fs.writeFileSync(outFile, buf);

  // 12px-wide LQIP so slow connections paint something immediately.
  const blur = await sharp(buf).resize(12).webp({ quality: 45 }).toBuffer();

  manifest.push({
    key: job.out,
    src: `/images/${job.out}.webp`,
    width: meta.width,
    height: meta.height,
    alt: job.alt,
    blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
  });

  console.log(
    `${job.out}.webp  ${meta.width}x${meta.height}  ${(buf.length / 1024).toFixed(0)}KB  (blur ${blur.length}B)`,
  );
}

const ts = `// AUTO-GENERATED by scripts/prep-real-images.mjs — do not edit by hand.
// Source photos are the real Uptech Consulting team/office photographs in
// public/images/real-image*.jpg, converted to WebP here. Each entry carries
// its intrinsic size so next/image can reserve layout space, and a 12px
// LQIP for slow connections.

export type SiteImage = {
  src: string;
  width: number;
  height: number;
  alt: string;
  blurDataURL: string;
};

export const images = {
${manifest
  .map(
    (m) => `  "${m.key}": {
    src: "${m.src}",
    width: ${m.width},
    height: ${m.height},
    alt: "${m.alt.replace(/"/g, '\\"')}",
    blurDataURL:
      "${m.blurDataURL}",
  },`,
  )
  .join("\n")}
} satisfies Record<string, SiteImage>;

export type ImageKey = keyof typeof images;
`;

fs.mkdirSync(path.join(ROOT, "lib"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "lib/images.ts"), ts);
